import type { SVGProps } from 'react'

type IconProps = SVGProps<SVGSVGElement>

// Íconos de trazo, decorativos (aria-hidden): el texto o el aria-label del botón los describe.
function Icon({ children, ...props }: IconProps) {
  return (
    <svg
      width="20"
      height="20"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2.2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  )
}

